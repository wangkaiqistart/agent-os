CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE sessions (
    session_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    profile_name text NOT NULL,
    channel text NOT NULL,
    user_id text NOT NULL,
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'archived')),
    lease_owner text,
    lease_until timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_active_at timestamptz NOT NULL DEFAULT now(),
    archived_at timestamptz
);
CREATE UNIQUE INDEX uq_sessions_active_key ON sessions(channel, user_id, profile_name) WHERE status = 'active';

CREATE TABLE agent_turns (
    turn_id uuid PRIMARY KEY,
    session_id uuid NOT NULL REFERENCES sessions(session_id),
    trigger text NOT NULL,
    status text NOT NULL CHECK (status IN ('RUNNING', 'SUCCEEDED', 'FAILED', 'TIMED_OUT', 'MAX_ITERATIONS', 'INTERRUPTED', 'LIMIT_EXCEEDED')),
    iterations int NOT NULL DEFAULT 0,
    final_text text,
    error_message text,
    started_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    deadline_at timestamptz NOT NULL
);
CREATE INDEX idx_agent_turns_session_started ON agent_turns(session_id, started_at DESC);
CREATE INDEX idx_agent_turns_running ON agent_turns(status) WHERE status = 'RUNNING';

CREATE TABLE session_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id uuid NOT NULL REFERENCES sessions(session_id),
    turn_id uuid NOT NULL REFERENCES agent_turns(turn_id),
    iteration int NOT NULL CHECK (iteration >= 0),
    type text NOT NULL CHECK (type IN ('USER', 'ASSISTANT', 'TOOL')),
    content text,
    tool_calls jsonb,
    tool_responses jsonb,
    metadata jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_session_messages_session_id ON session_messages(session_id, id);

CREATE TABLE llm_calls (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    write_id uuid NOT NULL UNIQUE,
    session_id uuid NOT NULL REFERENCES sessions(session_id),
    turn_id uuid NOT NULL REFERENCES agent_turns(turn_id),
    iteration int NOT NULL,
    provider text NOT NULL,
    requested_model text NOT NULL,
    response_model text,
    response_id text,
    mode text NOT NULL CHECK (mode IN ('CALL', 'STREAM')),
    attempt smallint NOT NULL CHECK (attempt IN (1, 2)),
    finish_reason text,
    tool_call_count int,
    image_count int NOT NULL,
    prompt_tokens int,
    completion_tokens int,
    total_tokens int,
    cache_read_tokens bigint,
    cache_write_tokens bigint,
    requests_remaining bigint,
    tokens_remaining bigint,
    output_cap_honored boolean,
    success boolean NOT NULL,
    failure_kind text,
    http_status int,
    error_message text,
    created_at timestamptz NOT NULL,
    duration_ms bigint NOT NULL
);

CREATE TABLE tool_invocations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id uuid NOT NULL REFERENCES sessions(session_id),
    turn_id uuid NOT NULL REFERENCES agent_turns(turn_id),
    iteration int NOT NULL,
    tool_call_id text NOT NULL,
    tool_name text NOT NULL,
    tool_source text NOT NULL,
    status text NOT NULL CHECK (status IN ('in_progress', 'success', 'failed', 'timeout', 'sandbox_denied', 'limit_skipped', 'interrupted', 'unconfirmed')),
    input_json jsonb,
    result_text text,
    result_chars int,
    result_truncated boolean NOT NULL DEFAULT false,
    error_message text,
    idempotent boolean NOT NULL,
    attempts smallint NOT NULL DEFAULT 0,
    duration_ms bigint,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_tool_invocation_key UNIQUE (turn_id, iteration, tool_call_id)
);
CREATE INDEX idx_tool_invocations_session_turn ON tool_invocations(session_id, turn_id);
CREATE INDEX idx_tool_invocations_in_progress ON tool_invocations(status) WHERE status = 'in_progress';
